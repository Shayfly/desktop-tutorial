"""M5 Task 6: provider-neutral contracts for generated-app infrastructure.

A Web/SaaS product generated by 148AI needs infrastructure of its own: a
relational database, application auth/session secrets, object storage,
scheduled/background HTTP work and outbound webhook/email delivery. This
module describes that need in a machine-readable, vendor-neutral way.

Truth rules enforced here:

* Bindings carry *references* to secrets (``env:`` / ``vault:``), never secret
  values. Public configuration is scanned for secret-looking material.
* A binding is only ``LIVE`` when a provisioner says it verified the resource.
  ``NOT_CONFIGURED`` and ``BLOCKED`` are explicit, never silently upgraded.
* Every binding is owned by exactly one tenant, project and environment.
  Preview and production never share a binding.
* A product with a missing or non-LIVE *required* binding is not ready.

The concrete provisioner for the first profile lives in
``omni_prod.providers.managed_web_saas``.
"""
