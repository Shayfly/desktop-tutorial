class InfrastructureKind(str, Enum):
    """Canonical, vendor-neutral infrastructure kinds.

    The values are exactly the ``kind`` strings ProductArchitect already writes
    into ``BuildContract.infrastructure`` (M5 Task 4), so contracts persisted
    before this module existed remain valid.
    """

    DATABASE = "database"
    AUTH_SESSION = "auth_session"
    OBJECT_STORAGE = "object_storage"
    SCHEDULED_HTTP = "scheduled_http"
    OUTBOUND = "outbound"


class InfrastructureEnvironment(str, Enum):
    PREVIEW = "preview"
    PRODUCTION = "production"


class BindingStatus(str, Enum):
    LIVE = "LIVE"
    NOT_CONFIGURED = "NOT_CONFIGURED"
    BLOCKED = "BLOCKED"
    REVOKED = "REVOKED"


_SECRET_REF_SCHEMES = frozenset({"env", "vault"})
_INLINE_SECRET_MARKERS = ("bearer ", "sk-live-", "sk-proj-", "sk-ant-", "-----begin")
_SENSITIVE_KEY_PARTS = ("secret", "password", "passwd", "token", "api_key", "apikey",
                        "authorization", "credential", "private_key", "dsn")
_URL_WITH_USERINFO = re.compile(r"[a-z][a-z0-9+.-]*://[^/\s:@]+:[^/\s@]+@", re.IGNORECASE)


def _now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def validate_secret_reference(reference: str) -> str:
    """Accept only ``env:NAME`` / ``vault:path`` references, never inline values."""
    text = str(reference)
    scheme, sep, remainder = text.partition(":")
    if not sep or scheme not in _SECRET_REF_SCHEMES or not remainder.strip():
        raise ValueError("secret reference must use an approved env: or vault: reference")
    if remainder.startswith("//") or _URL_WITH_USERINFO.search(text):
        raise ValueError("secret reference must not be a URL with credentials")
    lowered = text.lower()
    if any(marker in lowered for marker in _INLINE_SECRET_MARKERS):
        raise ValueError("secret reference must not contain inline credential material")
    if scheme == "env" and not re.fullmatch(r"[A-Z][A-Z0-9_]{0,127}", remainder):
        raise ValueError("env: secret reference must name an upper-case environment variable")
    if scheme == "vault" and (".." in remainder.split("/") or not re.fullmatch(r"[A-Za-z0-9_./-]{1,512}", remainder)):
        raise ValueError("vault: secret reference contains an invalid path")
    return text


def _assert_public_value_safe(key: str, value: Any) -> None:
    lowered_key = str(key).lower()
    if any(part in lowered_key for part in _SENSITIVE_KEY_PARTS):
        raise ValueError(f"public_config key {key!r} looks like secret material; store a secret reference instead")
    if isinstance(value, Mapping):
        for k, v in value.items():
            _assert_public_value_safe(f"{key}.{k}", v)
        return
    if isinstance(value, (list, tuple)):
        for item in value:
            _assert_public_value_safe(key, item)
        return
    if isinstance(value, str):
        lowered = value.lower()
        if _URL_WITH_USERINFO.search(value):
            raise ValueError(f"public_config value for {key!r} embeds credentials in a URL")
        if any(marker in lowered for marker in _INLINE_SECRET_MARKERS):
            raise ValueError(f"public_config value for {key!r} contains inline credential material")


def _coerce_kind(kind: InfrastructureKind | str) -> InfrastructureKind:
    try:
        return kind if isinstance(kind, InfrastructureKind) else InfrastructureKind(str(kind))
    except ValueError as exc:
        raise ValueError(f"unknown infrastructure kind: {kind}") from exc


def _coerce_environment(environment: InfrastructureEnvironment | str) -> InfrastructureEnvironment:
    try:
        return (environment if isinstance(environment, InfrastructureEnvironment)
                else InfrastructureEnvironment(str(environment)))
    except ValueError as exc:
        raise ValueError(f"unknown infrastructure environment: {environment}") from exc


def _project_digest(project_id: str) -> str:
    if not str(project_id).strip():
        raise ValueError("project_id is required")
    return sha256(f"148ai-generated-app\0{project_id}".encode("utf-8")).hexdigest()


def deterministic_resource_name(*, project_id: str, environment, kind) -> str:
    """Stable, identifier-safe resource name.

    The project id is hashed (it may be user-visible or contain characters a
    database or bucket would reject); environment and kind stay readable so an
    operator can see what a resource is for.
    """
    env = _coerce_environment(environment)
    k = _coerce_kind(kind)
    name = f"ga_{_project_digest(project_id)[:16]}_{env.value[:4]}_{k.value}"
    return name[:63]


def provisioning_idempotency_key(*, profile_key: str, project_id: str, environment, kind) -> str:
    env = _coerce_environment(environment)
    k = _coerce_kind(kind)
    if not str(profile_key).strip():
        raise ValueError("profile_key is required")
    source = f"m5-infra-v1\0{profile_key}\0{project_id}\0{env.value}\0{k.value}"
    return sha256(source.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class InfrastructureQuote:
    profile_key: str
    kind: InfrastructureKind
    environment: InfrastructureEnvironment
    estimated_monthly_usd: Decimal | None
    maximum_monthly_usd: Decimal | None
    basis: str
    # One-time variable cost of provisioning this binding for a build. This is
    # what build economics reserves; None means unknown and blocks the build.
    provisioning_estimated_usd: Decimal | None = None
    provisioning_maximum_usd: Decimal | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "kind", _coerce_kind(self.kind))
        object.__setattr__(self, "environment", _coerce_environment(self.environment))
        if (self.provisioning_estimated_usd is not None and self.provisioning_maximum_usd is not None
                and self.provisioning_maximum_usd < self.provisioning_estimated_usd):
            raise ValueError("provisioning_maximum_usd must be >= provisioning_estimated_usd")
        for name in ("estimated_monthly_usd", "maximum_monthly_usd", "provisioning_estimated_usd", "provisioning_maximum_usd"):
            value = getattr(self, name)
            if value is not None and value < 0:
                raise ValueError(f"{name} must be >= 0")
        if (self.estimated_monthly_usd is not None and self.maximum_monthly_usd is not None
                and self.maximum_monthly_usd < self.estimated_monthly_usd):
            raise ValueError("maximum_monthly_usd must be >= estimated_monthly_usd")
        if not self.basis.strip():
            raise ValueError("quote basis is required")

    def to_dict(self) -> dict[str, Any]:
        return {
            "profile_key": self.profile_key, "kind": self.kind.value, "environment": self.environment.value,
            "estimated_monthly_usd": None if self.estimated_monthly_usd is None else str(self.estimated_monthly_usd),
            "maximum_monthly_usd": None if self.maximum_monthly_usd is None else str(self.maximum_monthly_usd),
            "provisioning_estimated_usd": None if self.provisioning_estimated_usd is None else str(self.provisioning_estimated_usd),
            "provisioning_maximum_usd": None if self.provisioning_maximum_usd is None else str(self.provisioning_maximum_usd),
            "basis": self.basis,
        }


@dataclass(frozen=True)
class InfrastructureBinding:
    binding_id: str
    profile_key: str
    tenant_id: str
    project_id: str
    environment: InfrastructureEnvironment
    kind: InfrastructureKind
    status: BindingStatus
    resource_name: str
    idempotency_key: str
    provisioner: str
    secret_references: Mapping[str, str] = field(default_factory=dict)
    public_config: Mapping[str, Any] = field(default_factory=dict)
    evidence: Mapping[str, Any] = field(default_factory=dict)
    status_reason: str | None = None
    created_at: str = field(default_factory=_now_iso)
    revoked_at: str | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "kind", _coerce_kind(self.kind))
        object.__setattr__(self, "environment", _coerce_environment(self.environment))
        object.__setattr__(self, "status", BindingStatus(self.status))
        for name in ("binding_id", "profile_key", "tenant_id", "project_id", "resource_name",
                     "idempotency_key", "provisioner"):
            if not str(getattr(self, name)).strip():
                raise ValueError(f"{name} must not be empty")
        refs = {}
        for name, reference in dict(self.secret_references).items():
            if not str(name).strip():
                raise ValueError("secret reference names must not be empty")
            refs[str(name)] = validate_secret_reference(reference)
        object.__setattr__(self, "secret_references", refs)
        public = dict(self.public_config)
        for key, value in public.items():
            _assert_public_value_safe(key, value)
        object.__setattr__(self, "public_config", public)
        object.__setattr__(self, "evidence", dict(self.evidence))
        if self.status == BindingStatus.LIVE and not refs and not public.get("no_secret_material_required"):
            raise ValueError("a LIVE binding must expose at least one secret reference "
                             "(or declare no_secret_material_required)")
        if self.status == BindingStatus.REVOKED and not self.revoked_at:
            raise ValueError("a REVOKED binding requires revoked_at")

    @property
    def live(self) -> bool:
        return self.status == BindingStatus.LIVE

    def revoked(self, *, at: str | None = None, reason: str | None = None) -> "InfrastructureBinding":
        return replace(self, status=BindingStatus.REVOKED, revoked_at=at or _now_iso(),
                       status_reason=reason or self.status_reason)

    def to_record(self) -> dict[str, Any]:
        """Full durable record (references, not values) for the binding repository."""
        return {
            "binding_id": self.binding_id, "profile_key": self.profile_key, "tenant_id": self.tenant_id,
            "project_id": self.project_id, "environment": self.environment.value, "kind": self.kind.value,
            "status": self.status.value, "resource_name": self.resource_name,
            "idempotency_key": self.idempotency_key, "provisioner": self.provisioner,
            "secret_references": dict(self.secret_references), "public_config": dict(self.public_config),
            "evidence": dict(self.evidence), "status_reason": self.status_reason,
            "created_at": self.created_at, "revoked_at": self.revoked_at,
        }

    @classmethod
    def from_record(cls, data: Mapping[str, Any]) -> "InfrastructureBinding":
        return cls(
            binding_id=str(data["binding_id"]), profile_key=str(data["profile_key"]),
            tenant_id=str(data["tenant_id"]), project_id=str(data["project_id"]),
            environment=data["environment"], kind=data["kind"], status=data["status"],
            resource_name=str(data["resource_name"]), idempotency_key=str(data["idempotency_key"]),
            provisioner=str(data["provisioner"]),
            secret_references=dict(data.get("secret_references") or {}),
            public_config=dict(data.get("public_config") or {}),
            evidence=dict(data.get("evidence") or {}),
            status_reason=data.get("status_reason"),
            created_at=str(data.get("created_at") or _now_iso()),
            revoked_at=data.get("revoked_at"),
        )

    def to_public_dict(self) -> dict[str, Any]:
        """API/log/artifact-safe view: reference *names* only, never targets."""
        return {
            "binding_id": self.binding_id, "profile_key": self.profile_key,
            "environment": self.environment.value, "kind": self.kind.value,
            "status": self.status.value, "status_reason": self.status_reason,
            "resource_name": self.resource_name, "provisioner": self.provisioner,
            "secret_reference_names": sorted(self.secret_references),
            "public_config": dict(self.public_config),
            "created_at": self.created_at, "revoked_at": self.revoked_at,
        }


@dataclass(frozen=True)
class InfrastructureProfile:
    """A named, versioned set of infrastructure requirements with a dependency DAG."""

    key: str
    version: int
    description: str
    requirements: tuple[InfrastructureRequirement, ...]
    kind_dependencies: Mapping[InfrastructureKind, tuple[InfrastructureKind, ...]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not re.fullmatch(r"[a-z][a-z0-9_]*_v[0-9]+", self.key):
            raise ValueError("profile key must look like <name>_v<version>")
        if self.version < 1:
            raise ValueError("profile version must be >= 1")
        kinds = []
        for requirement in self.requirements:
            kinds.append(_coerce_kind(requirement.kind))
        if len(kinds) != len(set(kinds)):
            raise ValueError("profile requirements must not repeat a kind")
        deps = {}
        for kind, depends_on in dict(self.kind_dependencies).items():
            k = _coerce_kind(kind)
            values = tuple(_coerce_kind(d) for d in depends_on)
            for dependency in values:
                if dependency not in kinds:
                    raise ValueError(f"profile dependency {dependency.value} for {k.value} is not in the profile")
            deps[k] = values
        object.__setattr__(self, "kind_dependencies", deps)
        self.ordered_kinds()  # rejects cycles

    def requirement_for(self, kind) -> InfrastructureRequirement:
        k = _coerce_kind(kind)
        for requirement in self.requirements:
            if requirement.kind == k.value:
                return requirement
        raise KeyError(f"profile {self.key} has no requirement for {k.value}")

    def dependency_closure(self, kinds: Iterable[InfrastructureKind | str]) -> tuple[InfrastructureKind, ...]:
        """Dependencies-first closure, emitted in the profile's canonical order."""
        requested = [_coerce_kind(k) for k in kinds]
        profile_kinds = {_coerce_kind(r.kind) for r in self.requirements}
        for kind in requested:
            if kind not in profile_kinds:
                raise ValueError(f"kind {kind.value} is not part of profile {self.key}")
        needed: set[InfrastructureKind] = set()
        visiting: set[InfrastructureKind] = set()

        def visit(kind: InfrastructureKind) -> None:
            if kind in needed:
                return
            if kind in visiting:
                raise ValueError(f"infrastructure dependency cycle at {kind.value}")
            visiting.add(kind)
            for dependency in self.kind_dependencies.get(kind, ()):
                visit(dependency)
            visiting.discard(kind)
            needed.add(kind)

        for kind in requested:
            visit(kind)
        return tuple(k for k in self._topological_order() if k in needed)

    def _topological_order(self) -> tuple[InfrastructureKind, ...]:
        declared = [_coerce_kind(r.kind) for r in self.requirements]
        order: list[InfrastructureKind] = []
        emitted: set[InfrastructureKind] = set()
        visiting: set[InfrastructureKind] = set()

        def visit(kind: InfrastructureKind) -> None:
            if kind in emitted:
                return
            if kind in visiting:
                raise ValueError(f"infrastructure dependency cycle at {kind.value}")
            visiting.add(kind)
            for dependency in self.kind_dependencies.get(kind, ()):
                visit(dependency)
            visiting.discard(kind)
            emitted.add(kind)
            order.append(kind)

        for kind in declared:
            visit(kind)
        return tuple(order)

    def ordered_kinds(self) -> tuple[InfrastructureKind, ...]:
        return self._topological_order()

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key, "version": self.version, "description": self.description,
            "requirements": [r.to_dict() for r in self.requirements],
            "kind_dependencies": {k.value: [d.value for d in v] for k, v in self.kind_dependencies.items()},
            "ordered_kinds": [k.value for k in self.ordered_kinds()],
        }


@runtime_checkable
class InfrastructureProvisioner(Protocol):
    """Adapter boundary. Implementations must be idempotent per idempotency_key."""

    name: str
    profile_key: str
    supported_kinds: tuple[InfrastructureKind, ...]

    def quote(self, requirement: InfrastructureRequirement, *, project_id: str,
              environment) -> InfrastructureQuote: ...

    def provision(self, requirement: InfrastructureRequirement, *, tenant_id: str, project_id: str,
                  environment, idempotency_key: str) -> InfrastructureBinding: ...

    def status(self, binding: InfrastructureBinding) -> InfrastructureBinding: ...

    def revoke(self, binding: InfrastructureBinding) -> InfrastructureBinding: ...

    def readiness(self) -> Mapping[str, str]: ...


@dataclass(frozen=True)
class InfrastructureGateResult:
    ready: bool
    profile_key: str | None
    project_id: str
    environment: InfrastructureEnvironment
    missing_kinds: tuple[InfrastructureKind, ...]
    not_live: Mapping[InfrastructureKind, str]
    ownership_violations: tuple[str, ...]
    bindings: Mapping[InfrastructureKind, InfrastructureBinding]

    def to_dict(self) -> dict[str, Any]:
        return {
            "ready": self.ready,
            "profile_key": self.profile_key,
            "project_id": self.project_id,
            "environment": self.environment.value,
            "missing_kinds": [k.value for k in self.missing_kinds],
            "not_live": {k.value: v for k, v in self.not_live.items()},
            "ownership_violations": list(self.ownership_violations),
            "bindings": {k.value: b.to_public_dict() for k, b in self.bindings.items()},
            "truth_note": "LIVE only when the provisioner verified the resource; secrets are references only.",
        }


def evaluate_infrastructure_readiness(
    requirements: Iterable[InfrastructureRequirement],
    bindings: Iterable[InfrastructureBinding],
    *,
    project_id: str,
    environment,
    profile_key: str | None = None,
    tenant_id: str | None = None,
) -> InfrastructureGateResult:
    """Pure READY gate: every required kind needs an owned, LIVE binding."""
    env = _coerce_environment(environment)
    reqs = tuple(requirements)
    violations: list[str] = []
    usable: dict[InfrastructureKind, InfrastructureBinding] = {}
    for binding in bindings:
        problem = None
        if binding.project_id != project_id:
            problem = f"{binding.binding_id}: owned by another project"
        elif binding.environment != env:
            problem = f"{binding.binding_id}: belongs to {binding.environment.value}, not {env.value}"
        elif tenant_id is not None and binding.tenant_id != tenant_id:
            problem = f"{binding.binding_id}: owned by another tenant"
        elif profile_key is not None and binding.profile_key != profile_key:
            problem = f"{binding.binding_id}: provisioned for profile {binding.profile_key}"
        if problem:
            violations.append(problem)
            continue
        current = usable.get(binding.kind)
        # Prefer a LIVE binding over a stale non-live record of the same kind.
        if current is None or (not current.live and binding.live):
            usable[binding.kind] = binding

    missing: list[InfrastructureKind] = []
    not_live: dict[InfrastructureKind, str] = {}
    for requirement in reqs:
        kind = _coerce_kind(requirement.kind)
        binding = usable.get(kind)
        if binding is None:
            if requirement.required:
                missing.append(kind)
            continue
        if not binding.live and requirement.required:
            not_live[kind] = binding.status.value

    required_present = not missing and not not_live
    ready = required_present and not violations
    return InfrastructureGateResult(
        ready=ready, profile_key=profile_key, project_id=project_id, environment=env,
        missing_kinds=tuple(missing), not_live=not_live, ownership_violations=tuple(violations),
        bindings=usable,
    )
