"""Read-only view of the generated registries the planner decides from.

Sources (all generated by their canonical generators and checked in CI):
AGENT_OS_REGISTRY.json (agents + skills with computed status),
TRUTH_MATRIX.json (customer capabilities), PROVIDER_MATRIX.json (models).
If a file is missing (e.g. stripped from a deployment bundle) every status
reads UNKNOWN, which makes feasibility UNKNOWN -- never FEASIBLE by default.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERIFIED = ('REAL_SERVER_VERIFIED', 'LIVE')
EXECUTABLE = ('IMPLEMENTED', 'UNIT_TESTED', 'INTEGRATION_TESTED', 'REAL_SERVER_VERIFIED', 'LIVE')


def _load(name: str):
    try:
        return json.loads((ROOT / name).read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None


@lru_cache(maxsize=1)
def snapshot() -> dict:
    reg = _load('AGENT_OS_REGISTRY.json') or {}
    truth = _load('TRUTH_MATRIX.json') or {}
    prov = _load('PROVIDER_MATRIX.json') or {}
    return {
        'agents': {a['agent_key']: a for a in reg.get('agents', [])},
        'skills': {s['skill_key']: s for s in reg.get('skills', [])},
        'capabilities': {r['capability']: r for r in truth.get('rows', [])},
        'models': prov.get('models', []),
        'gaps': {g['capability']: g for g in prov.get('capability_gaps', [])},
        'loaded': bool(reg and truth and prov),
    }


def agent_status(key: str) -> str:
    return (snapshot()['agents'].get(key) or {}).get('status', 'UNKNOWN')


def skill_status(key: str) -> str:
    return (snapshot()['skills'].get(key) or {}).get('status', 'UNKNOWN')


def capability_status(name: str) -> str:
    return (snapshot()['capabilities'].get(name) or {}).get('status', 'UNKNOWN')


def allowed_skills() -> dict[str, set[str]]:
    return {k: set(a.get('allowed_skills') or ()) for k, a in snapshot()['agents'].items()}


def skill_keys() -> set[str]:
    return set(snapshot()['skills'])


def models_for(task: str) -> list[dict]:
    """Routable models for a task class: in the catalog, AVAILABLE, eligible."""
    return [m for m in snapshot()['models']
            if m.get('in_worker_catalog') and m.get('availability') == 'AVAILABLE' and task in (m.get('eligible_tasks') or [])]
