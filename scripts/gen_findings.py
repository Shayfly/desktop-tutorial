"""FINDINGS.md is GENERATED, never hand-written (owner idea, 2026-10-28).

Sources: TRUTH_MATRIX.json (rows BLOCKED / NOT_IMPLEMENTED, with the blocking part's `why`), PROVIDER_MATRIX.json
(capability_gaps, models with a `blocker`) and AGENT_OS_REGISTRY.json (agents BLOCKED). One line per finding:
  id | severity | what | blocked_on | owner_actionable | status
owner_actionable=yes first. Severity and owner_actionable are derived by fixed rules (below), not chosen by hand.

  python scripts/gen_findings.py            # write FINDINGS.md
  python scripts/gen_findings.py --check    # exit 1 when FINDINGS.md is stale versus the registries
  python scripts/gen_findings.py --notice   # also print each finding as a ::notice (deploy)
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'FINDINGS.md'
# Owner-actionable = the blocker is something the owner can do himself (an account, a credit, a key, a setting, a
# contract or a decision), not engineering work.
OWNER = re.compile(r'founder|owner|credit|balance|billing|account|contract|licen[cs]|decision|not configured|'
                   r'configure|key|token|no provider selected|commercial', re.I)


def _row(fid, severity, what, blocked_on, status):
    actionable = 'yes' if blocked_on and OWNER.search(blocked_on) else 'no'
    clean = lambda s: ' '.join(str(s or '-').replace('|', '/').split())
    return {'id': fid, 'severity': severity, 'what': clean(what), 'blocked_on': clean(blocked_on),
            'owner_actionable': actionable, 'status': status}


def findings() -> list[dict]:
    out = []
    truth = json.loads((ROOT / 'TRUTH_MATRIX.json').read_text(encoding='utf-8'))
    for r in truth['rows']:
        if r['status'] not in ('BLOCKED', 'NOT_IMPLEMENTED'):
            continue
        why = '; '.join(p.get('why', '') for p in r.get('parts', []) if p.get('status') == r['status']) or r.get('note')
        sev = ('high' if r.get('shown_to_customer') else 'medium') if r['status'] == 'BLOCKED' else \
              ('medium' if r.get('shown_to_customer') else 'low')
        out.append(_row(f"TRUTH:{r['capability']}", sev, r['requirement'], why, r['status']))
    prov = json.loads((ROOT / 'PROVIDER_MATRIX.json').read_text(encoding='utf-8'))
    for g in prov.get('capability_gaps', []):
        out.append(_row(f"PROVIDER:{g['capability']}", 'medium' if g['state'] == 'BLOCKED' else 'low',
                        f"capability {g['capability']}", g.get('note'), g['state']))
    for m in prov.get('models', []):
        if m.get('blocker'):
            out.append(_row(f"PROVIDER:{m['model_key']}", 'medium', f"model {m['provider_model_id']} ({m['provider_key']})",
                            f"{m['blocker']} (as of {m.get('last_verified_at')})", m.get('availability', 'BLOCKED')))
    agents = json.loads((ROOT / 'AGENT_OS_REGISTRY.json').read_text(encoding='utf-8'))
    for a in agents['agents']:
        if a['status'] == 'BLOCKED':
            out.append(_row(f"AGENT:{a['agent_key']}", 'low', a['name'], a.get('why'), 'BLOCKED'))
    rank = {'high': 0, 'medium': 1, 'low': 2}
    return sorted(out, key=lambda f: (f['owner_actionable'] != 'yes', rank[f['severity']], f['id']))


def render(rows) -> str:
    lines = ['# FINDINGS', '',
             '<!-- GENERATED by scripts/gen_findings.py from TRUTH_MATRIX.json, PROVIDER_MATRIX.json and '
             'AGENT_OS_REGISTRY.json. Do not edit by hand: CI fails when this file is stale. -->', '',
             '| id | severity | what | blocked_on | owner_actionable | status |', '|---|---|---|---|---|---|']
    lines += [f"| {f['id']} | {f['severity']} | {f['what']} | {f['blocked_on']} | {f['owner_actionable']} | {f['status']} |"
              for f in rows]
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    rows = findings()
    text = render(rows)
    if '--check' in argv:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if current != text:
            print('::error title=FINDINGS.md::stale or hand-edited; run python scripts/gen_findings.py and commit it')
            return 1
        print(f'FINDINGS.md is current ({len(rows)} findings)')
    else:
        OUT.write_text(text, encoding='utf-8')
    if '--notice' in argv:
        for f in rows:
            print(f"::notice title=finding {f['id']}::{f['severity']} owner_actionable={f['owner_actionable']} "
                  f"{f['status']} - {f['what']} - blocked on: {f['blocked_on']}"[:900])
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
