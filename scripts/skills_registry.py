"""skills/REGISTRY.md, the "built" table (the owner, 2026-11-17: three columns only -- id | gate | failureCode).

AGENTS.md rule 3: status is derived, never hand-written. The BUILT rows are read from the code that enforces them:
every skill unit's manifest (its gate) and failure_codes.json, plus the checks that are not units but emit their own
codes (G-APPLE's static and render rules, G8, the game gate, A4). The TARGET rows -- skills the owner listed that are
not built yet -- are the hand-kept part of the file, below the generated block, and are checked for shape only.

    python scripts/skills_registry.py            # print the generated block
    python scripts/skills_registry.py --write    # rewrite the block in skills/REGISTRY.md
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / 'skills' / 'REGISTRY.md'
BEGIN, END = '<!-- built:begin (generated by scripts/skills_registry.py) -->', '<!-- built:end -->'


def built_rows() -> list[tuple[str, str, str]]:
    sys.path.insert(0, str(ROOT))
    rows: list[tuple[str, str, str]] = []
    units = ROOT / 'omni_prod' / 'skill_units'
    for unit in sorted(p for p in units.iterdir() if (p / 'manifest.json').is_file()):
        manifest = json.loads((unit / 'manifest.json').read_text(encoding='utf-8'))
        codes = json.loads((unit / 'failure_codes.json').read_text(encoding='utf-8'))
        for code in sorted(codes):
            rows.append((manifest['name'], manifest['gate'], code))
    from omni_prod import game_runtime, runtime_load
    from omni_prod.g_apple import render
    static = (ROOT / 'omni_prod' / 'g_apple' / 'static.py').read_text(encoding='utf-8')
    static_codes = sorted(set(re.findall(r"add\('([A-Z0-9_]+)'", static)) - {'UNREADABLE'})
    rows += [('g_apple.static', 'APPLE', c) for c in static_codes]
    rows += [('g_apple.render', 'APPLE', c) for c in sorted(render.CODES)]
    rows += [('g_apple.reviewer.typography_layout', 'APPLE', 'REVIEW_typography_layout'),
             ('g_apple.reviewer.brand_category', 'APPLE', 'REVIEW_brand_category')]
    rows += [('runtime_load', 'G8', c) for c in sorted(runtime_load.CODES)]
    rows += [('game_runtime', 'GAME', c) for c in sorted(game_runtime.CODES)]
    rows += [('a4.placement', 'A4', 'not_first'), ('a4.placement', 'A4', 'no_section'), ('a4.placement', 'A4', 'wrong_section')]
    return rows


def block() -> str:
    lines = [BEGIN, '| id | gate | failureCode |', '|---|---|---|']
    lines += [f'| {i} | {g} | {c} |' for i, g, c in built_rows()]
    return '\n'.join(lines + [END])


def main(argv) -> int:
    text = block()
    if '--write' not in argv:
        print(text)
        return 0
    current = REGISTRY.read_text(encoding='utf-8')
    if BEGIN not in current or END not in current:
        print(f'::error title=skills registry::{REGISTRY} has no generated block markers')
        return 1
    start, end = current.index(BEGIN), current.index(END) + len(END)
    REGISTRY.write_text(current[:start] + text + current[end:], encoding='utf-8')
    print(f'wrote {REGISTRY} ({len(built_rows())} built rows)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
