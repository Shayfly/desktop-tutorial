/* C4 (2026-10-27): the approval screen in real Chromium with the real index.html + app.js.
   Fixture = tests/approval_screen_fixture.json, generated by the server code (tests/approval_screen_fixture.py).
   Asserts: every locked item is one rendered row; assumptions are marked; every row has a "change" button;
   the approval request carries the fingerprint of the screen shown. Negative controls: a summary that locks more
   than it shows disables approval; a stale screen sends no fingerprint. APPROVAL_SHOT=<path> saves the screenshot. */
const {chromium}=require('playwright');
const fs=require('fs');
const assert=require('node:assert/strict');
const path=require('path');
(async()=>{
 const fx=JSON.parse(fs.readFileSync(path.join(__dirname,'approval_screen_fixture.json'),'utf8'));
 const ap=fx.view.summary.approval;
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-gpu']}:{})});
 try {
  async function open(view, plan, width=1440){
   const page=await browser.newPage({viewport:{width,height:1600}});
   const approvals=[];
   await page.route('**/*',async route=>{
    const u=new URL(route.request().url());
    if(u.pathname==='/api/v28/me')return route.fulfill({status:401,contentType:'application/json',body:'{}'});
    if(u.pathname.endsWith('/approvals')){approvals.push(route.request().postDataJSON());
      return route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:{error:'approval_not_shown'}})});}
    if(u.pathname==='/fixture')return route.fulfill({contentType:'text/html',body:fs.readFileSync(path.join(__dirname,'../omni_prod/assets/index.html'),'utf8')});
    if(u.pathname.startsWith('/assets/'))return route.fulfill({path:path.join(__dirname,'../omni_prod',u.pathname)});
    return route.fulfill({status:404,body:''});
   });
   await page.addInitScript(()=>{const f=window.fetch.bind(window);window.fetch=(i,n)=>{const p=f(i,n);
     if(String(i).endsWith('/api/v28/me'))window.__meHandled=p.then(r=>{const t=r.text.bind(r);
       r.text=()=>{const b=t();window.__meHandled=b.then(()=>new Promise(res=>setTimeout(res,0)),()=>{});return b;};return r;},()=>{});
     return p;};});
   await page.goto('http://fixture.test/fixture');
   await page.waitForFunction(()=>window.__meHandled!==undefined);
   await page.evaluate(async()=>{let m;do{m=window.__meHandled;await m;}while(m!==window.__meHandled);});
   await page.evaluate(([v,p])=>{S.projectId='p';S.lang='he';S.disc=v;S.plan=p;S.chat={messages:[]};
     S.signedIn=true;S.me={email:'fixture@example.test'};showView();renderDiscovery();renderPlan();renderTabs();openTab('plan');},[view,plan]);
   return {page,approvals};
  }

  // 1. displayed = locked
  for(const width of [390,1440]){
   const {page,approvals}=await open(fx.view,fx.plan,width);
   const rows=page.locator('#approvalItems > li');
   assert.equal(await rows.count(),ap.locked_count,'one rendered row per locked item');
   assert.deepEqual(await rows.evaluateAll(els=>els.map(e=>e.dataset.key)),ap.items.map(x=>x.key),'same items, same order');
   assert.equal(await page.locator('#approvalCount').textContent(),`מוצגים ${ap.locked_count} פריטים · האישור נועל ${ap.locked_count} פריטים`);
   assert.equal(await page.locator('#approvalItems > li.assumed').count(),ap.items.filter(x=>x.assumed).length,'assumptions marked');
   assert.equal(await page.locator('#approvalItems > li button').count(),ap.locked_count,'every row editable');
   for(const r of await rows.all()){   // one line each: label, value, mark, change -- nothing else
     assert.equal(await r.locator(':scope > *').count(),4);
   }
   assert.equal(await page.locator('#confirmBtn').isDisabled(),false);
   for(const r of await rows.all()){   // one line: all four parts share one row (same top within a few px)
     const box=await r.locator(':scope > *').evaluateAll(els=>els.map(e=>{const b=e.getBoundingClientRect();return [b.top,b.bottom];}));
     assert.ok(Math.max(...box.map(b=>b[0]))<Math.min(...box.map(b=>b[1])),'label, value, mark and change share one row');
   }
   if(process.env.APPROVAL_SHOT){   // a viewport tall enough that the side panel shows the whole list unscrolled
     await page.setViewportSize({width,height:2600});
     await page.locator('#planPanel').screenshot({path:process.env.APPROVAL_SHOT.replace(/\.png$/,`-${width}.png`)});
   }
   await page.locator('#confirmBtn').click();
   await page.waitForFunction(()=>!buildStarting);
   assert.equal(approvals.length,1);
   assert.equal(approvals[0].shown_fingerprint,ap.fingerprint,'approval carries the fingerprint of the screen shown');
   assert.equal(approvals[0].brief_revision,1);
   // "change" on one row opens the edit form at that decision
   await page.evaluate(()=>{openTab('plan');renderPlan();});
   await page.locator('#approvalItems > li[data-key="field:color"] button').click();
   await page.waitForFunction(()=>S.tab==='req');
   assert.equal(await page.evaluate(()=>document.activeElement&&document.activeElement.name),'q_color');
   await page.close();
  }

  // 2. negative control: the server says it locks one item more than it shows -> approval refused in the UI
  {
   const v=JSON.parse(JSON.stringify(fx.view));v.summary.approval.locked_count+=1;
   const {page}=await open(v,fx.plan);
   assert.equal(await page.locator('#confirmBtn').isDisabled(),true,'shown != locked blocks approval');
   assert.match(await page.locator('#planMsg').textContent(),/אינו כל מה שננעל/);
   if(process.env.APPROVAL_SHOT)await page.setViewportSize({width:1440,height:2600});
   if(process.env.APPROVAL_SHOT)await page.locator('#planPanel').screenshot({path:process.env.APPROVAL_SHOT.replace(/\.png$/,'-mismatch.png')});
   await page.close();
  }

  // 3. negative control: the plan is for another revision than the screen -> no fingerprint is sent (server refuses)
  {
   const p=JSON.parse(JSON.stringify(fx.plan));p.brief_revision=2;
   const {page,approvals}=await open(fx.view,p);
   await page.locator('#confirmBtn').click();
   await page.waitForFunction(()=>!buildStarting);
   assert.equal(approvals[0].shown_fingerprint,null,'a stale screen cannot vouch for a newer revision');
   assert.match(await page.locator('#planMsg').textContent()+await page.locator('#buildMsg').textContent(),/הסיכום השתנה/);
   await page.close();
  }
  console.log(`approval screen: ${ap.locked_count} shown = ${ap.locked_count} locked, ${ap.items.filter(x=>x.assumed).length} assumptions; fingerprint ${ap.fingerprint.slice(0,16)}`);
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
