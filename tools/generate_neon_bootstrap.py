"""Regenerate infra/staging/bootstrap_neon_empty.sql from infra/postgres/*.sql.

The bootstrap applies every migration to an EMPTY Neon database in one
transaction and records each migration's exact SHA-256 in schema_migrations,
so the normal checksum-verified runner (omni_prod.migrate) treats them as
applied. `infra/staging/verify_neon_bootstrap.py` (Neon bootstrap CI) fails on
any drift, so run this after adding a migration:

    python3 tools/generate_neon_bootstrap.py           # write
    python3 tools/generate_neon_bootstrap.py --check   # exit 1 on drift
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "infra/staging/bootstrap_neon_empty.sql"

HEADER = """-- 148AI: bootstrap an EMPTY public schema only.
-- Generated by tools/generate_neon_bootstrap.py from infra/postgres/*.sql.
-- Run the ENTIRE file once in Neon SQL Editor. No credentials are included.
-- A failure rolls back the transaction. Existing public tables cause an error.
BEGIN;
SET LOCAL search_path = public;
SELECT pg_advisory_xact_lock(781234991);
DO $bootstrap_guard$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
    ) THEN
        RAISE EXCEPTION 'Bootstrap requires an empty public schema. No changes applied.';
    END IF;
END;
$bootstrap_guard$;
"""

FOOTER = """COMMIT;

SELECT count(*) AS applied_migrations FROM schema_migrations;
SELECT version, name FROM schema_migrations ORDER BY version;
"""


def render() -> str:
    sources = sorted((ROOT / "infra/postgres").glob("*.sql"))
    parts = [HEADER]
    for path in sources:
        raw = path.read_bytes().decode("utf-8")
        parts.append("\n-- BEGIN SOURCE " + path.name + "\n" + raw + "\n-- END SOURCE " + path.name + "\n")
    parts.append("\n-- Record exact original migration checksums for the normal migration runner.\n")
    for path in sources:
        version, name = path.stem.split("_", 1)
        tag = "$source_" + version + "$"
        raw = path.read_bytes().decode("utf-8")
        if tag in raw:
            raise SystemExit("dollar-quote tag collides with source: " + path.name)
        parts.append("INSERT INTO schema_migrations(version, name, sha256)\n"
                     "VALUES (" + str(int(version)) + ", '" + name + "', encode(sha256(convert_to("
                     + tag + raw + tag + ", 'UTF8')), 'hex'));\n\n")
    parts.append(FOOTER)
    return "".join(parts)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            print("bootstrap drift: run python3 tools/generate_neon_bootstrap.py")
            sys.exit(1)
        print("bootstrap up to date")
    else:
        TARGET.write_text(text)
        print("wrote", TARGET.relative_to(ROOT))
